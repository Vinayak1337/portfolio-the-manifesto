import { mkdir, readdir, rename, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const projectRoot = process.cwd();
const assetsDir = path.join(projectRoot, "public", "assets");
const rawDir = path.join(assetsDir, "raw");
const blurMapPath = path.join(projectRoot, "src", "constants", "image-blurs.ts");
const maximumBytes = 290 * 1024;

await mkdir(rawDir, { recursive: true });

const assetNames = await readdir(assetsDir);
for (const name of assetNames.filter((entry) => entry.endsWith(".png")).sort()) {
  await rename(path.join(assetsDir, name), path.join(rawDir, name));
}

const sourceNames = (await readdir(rawDir))
  .filter((name) => name.endsWith(".png"))
  .sort();
const blurEntries = [];

for (const sourceName of sourceNames) {
  const sourcePath = path.join(rawDir, sourceName);
  const outputName = sourceName.replace(/\.png$/u, ".webp");
  const outputPath = path.join(assetsDir, outputName);
  let width = 1600;
  let quality = 76;

  while (true) {
    await sharp(sourcePath)
      .resize({ width, withoutEnlargement: true })
      .webp({ effort: 6, quality, smartSubsample: true })
      .toFile(outputPath);

    if ((await stat(outputPath)).size <= maximumBytes || quality <= 58) {
      break;
    }

    quality -= 6;
    if (quality < 64) width = 1400;
  }

  const blur = await sharp(outputPath)
    .resize({ width: 24, withoutEnlargement: true })
    .webp({ effort: 4, quality: 28 })
    .toBuffer();
  blurEntries.push([
    `/assets/${outputName}`,
    `data:image/webp;base64,${blur.toString("base64")}`,
  ]);
}

// SVG filters are expensive to rasterize while their card scrolls into view.
// Preserve the artwork exactly, but ship a pre-rasterized version for the rail.
for (const sourceName of ["nutrilife-preview.svg"]) {
  const outputName = sourceName.replace(/\.svg$/u, ".webp");
  const outputPath = path.join(assetsDir, outputName);
  await sharp(path.join(assetsDir, sourceName), { density: 96 })
    .resize({ width: 1600, withoutEnlargement: true })
    .webp({ effort: 6, quality: 76, smartSubsample: true })
    .toFile(outputPath);

  const blur = await sharp(outputPath)
    .resize({ width: 24, withoutEnlargement: true })
    .webp({ effort: 4, quality: 28 })
    .toBuffer();
  blurEntries.push([
    `/assets/${outputName}`,
    `data:image/webp;base64,${blur.toString("base64")}`,
  ]);
}

const generated = [
  "// Generated by scripts/optimize-project-images.mjs.",
  "export const imageBlurDataURLs: Readonly<Record<string, string>> = {",
  ...blurEntries.map(([src, data]) => `  ${JSON.stringify(src)}: ${JSON.stringify(data)},`),
  "};",
  "",
].join("\n");

await writeFile(blurMapPath, generated);

let seed = 0x1337;
const noiseSize = 96;
const noise = Buffer.alloc(noiseSize * noiseSize * 4);
for (let index = 0; index < noise.length; index += 4) {
  seed ^= seed << 13;
  seed ^= seed >>> 17;
  seed ^= seed << 5;
  const value = 180 + (seed & 0x4f);
  noise[index] = value;
  noise[index + 1] = value;
  noise[index + 2] = value;
  noise[index + 3] = 48 + ((seed >>> 8) & 0x3f);
}

await sharp(noise, { raw: { width: noiseSize, height: noiseSize, channels: 4 } })
  .webp({ effort: 6, quality: 58, alphaQuality: 65 })
  .toFile(path.join(assetsDir, "noise.webp"));

console.log(`Optimized ${sourceNames.length} project screenshots.`);
